/* ============================================================
   📚 books-et-16.js — اصلاح فصل‌های ۷ و ۸
   ------------------------------------------------------------
   ch7: اصلاح FEN پازل اول (شاه روی e5 بود، باید e8 باشد)
   ch8: بازنویسی پازل ۴۳ (کاملاً اشتباه بود) و اصلاح پازل ۴۵
   ساخته شده توسط امید گروسی
   ============================================================ */

(function() {

  const book = BOOKS_DB.find(b => b.id === 'essential-tactics');
  if(!book) { console.error('essential-tactics پیدا نشد'); return; }

  /* ============================================================
     📗 فصل ۷ — Observe Small Differences (تمرین‌های ۴۰ تا ۴۲)
     ============================================================ */

  const ch7 = book.chapters.find(c => c.id === 'ch7');
  if(ch7) {
    /* --- اصلاح پازل ۱: FEN اشتباه (شاه روی e5 بود) --- */
    const p1 = ch7.lessons.find(l => l.id === 'et-ch7-p1');
    if(p1) {
      p1.fen = '4k3/4P3/3P1K2/8/8/8/8/8 w - - 0 1';
      p1.solution = ['d6d7', 'e8d7', 'f6f7'];
      p1.solutionSan = '1. d7+ Kxd7 2. Kf7 (و پیادهٔ e7 ارتقا می‌یابد)';
      p1.explanation = 'd7+ یک «انحراف» (Deflection) کلاسیک است: شاه مشکی را از کنترل خانهٔ f7 دور می‌کند. مشکی چاره‌ای جز Kxd7 ندارد — چون خانه‌های d8 و f8 زیر ضرب پیادهٔ e7 هستند و f7 زیر ضرب شاه سفید f6. سپس 2.Kf7 و پیادهٔ e7 آزادانه به e8 می‌رسد و ارتقا می‌یابد. هشدار: 1.Ke6?? پات می‌کند! (شاه مشکی هیچ حرکت قانونی ندارد). نمونهٔ کلاسیک «یک حرکت اشتباه، برد را به تساوی تبدیل می‌کند».';
    }
  }

  /* ============================================================
     📗 فصل ۸ — Overcoming Resistance (تمرین‌های ۴۳ تا ۴۶)
     ============================================================ */

  const ch8 = book.chapters.find(c => c.id === 'et-ch8' || c.id === 'ch8');
  if(!ch8) { console.error('ch8 پیدا نشد'); return; }

  /* پازل ۴۳ را حذف کن (کاملاً اشتباه بود) */
  ch8.lessons = ch8.lessons.filter(l => l.id !== 'et-ch8-p43');

  /* پازل ۴۳ اصلاح‌شده — مطابق راه‌حل کتاب: Bxe7+ Kxe7 Nxf5+ */
  ch8.lessons.push({
    id: 'et-ch8-p43',
    type: 'puzzle',
    title: 'تمرین ۴۳ — حذف مدافع با کیش',
    fen: '3k4/4b3/8/5n2/1B1N4/8/6K1/8 w - - 0 1',
    text: ['سفید فیل در b4، اسب در d4، شاه در g2. مشکی فیل در e7، اسب در f5، شاه در d8. یک ترکیب پیدا کن که یک مهرهٔ کامل به دست دهد.'],
    solution: ['b4e7', 'd8e7', 'd4f5'],
    solutionSan: '1. Bxe7+ Kxe7 2. Nxf5+',
    hint: 'فیل و اسب مشکی از هم دفاع می‌کنند. اول فیل را با کیش بزن تا مشکی فرصت دفاع نداشته باشد، سپس اسب را شکار کن.',
    explanation: 'Bxe7+ یک «حذف مدافع» (Remove the Defender) کلاسیک است. فیل مشکی e7 توسط اسب f5 دفاع می‌شود و اسب f5 هم توسط فیل e7. سفید با Bxe7+ ابتدا فیل را می‌گیرد و کیش می‌دهد (روی قطر b4-c5-d6-e7-f8... نه، e7 به d8 یک حرکت قطری است: e7-d8. بله، کیش می‌دهد). مشکی چاره‌ای جز Kxe7 ندارد (اگر شاه به c7 یا e8 فرار کند، سفید در ادامه اسب f5 را با Bxf5 یا Nxf5 می‌گیرد). حالا اسب f5 بدون مدافع است: 2.Nxf5+ — اسب d4 اسب f5 را می‌گیرد و هم‌زمان شاه e7 را کیش می‌دهد. سفید یک مهره جلو افتاد و پایان‌بازی برنده دارد. الگوی کلیدی: «مدافع را با کیش حذف کن — حریف فرصت دفاع ندارد.»'
  });

  /* اصلاح پازل ۴۵ — solution قبلی حرکت نامعتبر e3a7 داشت */
  const p45 = ch8.lessons.find(l => l.id === 'et-ch8-p45');
  if(p45) {
    p45.fen = '8/k7/1p4p1/8/2b2P2/8/8/2B1K3 w - - 0 1';
    p45.solution = ['c1e3', 'c4b5', 'e3b6', 'a7b6', 'f4f5', 'g6f5', 'e1f2'];
    p45.solutionSan = '1. Be3+ (سیخ) Kb7 2. Bxb6 (تعویض فیل‌ها)';
    p45.explanation = 'Be3+ یک سیخ است: فیل c1 به e3 می‌رود و شاه a7 را روی قطر e3-d4-c5-b6-a7 کیش می‌دهد. مشکی باید شاه را از کیش خارج کند (Kb7 یا Ka6). سپس سفید با Bxb6 پیادهٔ b6 را می‌گیرد و فیل‌ها تعویض می‌شوند. حالا به یک پایان‌بازی پیاده‌ای می‌رسیم که در آن شاه سفید می‌تواند پیادهٔ مشکی g6 را بگیرد و پیادهٔ f4 خودش را به ارتقا برساند. نکته: «فیل در تعویض برابر، بازی را به یک پایان‌بازی برنده تبدیل می‌کند — گاهی بهترین راه، ساده‌سازی است.»';
  }

  /* مرتب‌سازی نهایی */
  ch8.lessons.sort((a, b) => {
    if(a.type === 'read' && b.type !== 'read') return -1;
    if(a.type !== 'read' && b.type === 'read') return 1;
    const numA = parseInt((a.id.match(/p(\d+)$/) || [0, 0])[1], 10);
    const numB = parseInt((b.id.match(/p(\d+)$/) || [0, 0])[1], 10);
    return numA - numB;
  });

  console.log('✅ فصل‌های ۷ و ۸ اصلاح شدند — ' + ch7.lessons.length + ' و ' + ch8.lessons.length + ' درس');

})();